import type { DOMLike, DOMLikeElement, HTMLSpec, Node, NodeSpec } from '@scriba/core'
import { mathmlSpec } from './mathml.js'

/**
 * KaTeX, as you import it (`import katex from 'katex'`, or `await import('katex')` to
 * load it only when needed). The plugin uses its MathML tree (`__renderToDomTree`), not
 * an HTML string, so the editor builds the output itself.
 */
export interface MathRenderer {
  renderToString(expression: string, options?: object): string
}

type TreeRenderer = (expression: string, options: Record<string, unknown>) => unknown

function treeRenderer(katex: MathRenderer): TreeRenderer {
  const render = (katex as unknown as { __renderToDomTree?: unknown }).__renderToDomTree
  if (typeof render !== 'function')
    throw new TypeError('This KaTeX version has no __renderToDomTree (use KaTeX 0.16 or later)')
  return render.bind(katex) as TreeRenderer
}

export const MAX_LATEX = 4000

/**
 * The only options KaTeX ever runs with: no `\href`, `\url`, `\includegraphics`,
 * `\htmlClass`… (`trust: false`), limits against macro bombs, MathML only.
 */
function katexOptions(display: boolean): Record<string, unknown> {
  return {
    output: 'mathml',
    displayMode: display,
    throwOnError: false,
    trust: false,
    strict: 'ignore',
    maxExpand: 1000,
    maxSize: 50,
    globalGroup: false,
  }
}

const isLatex = (v: unknown) =>
  typeof v === 'string' &&
  v.length <= MAX_LATEX &&
  ![...v].some((c) => c.charCodeAt(0) < 32 && c !== '\n' && c !== '\t')

/** The LaTeX source of a saved formula: the text of its `annotation` (application/x-tex). */
function latexOf(math: DOMLikeElement): string | null {
  let found: string | null = null
  const text = (node: DOMLike, depth: number): string => {
    if (depth > 10) return ''
    if (node.nodeType === 3) return node.nodeValue ?? ''
    let out = ''
    for (let i = 0; i < node.childNodes.length; i++) out += text(node.childNodes[i]!, depth + 1)
    return out
  }
  const walk = (node: DOMLike, depth: number) => {
    if (found !== null || depth > 30) return
    for (let i = 0; i < node.childNodes.length; i++) {
      const child = node.childNodes[i] as DOMLike & Partial<DOMLikeElement>
      if (child.nodeType !== 1) continue
      if (
        child.nodeName.toLowerCase() === 'annotation' &&
        child.getAttribute?.('encoding') === 'application/x-tex'
      ) {
        found = text(child, 0)
        return
      }
      walk(child, depth + 1)
    }
  }
  walk(math, 0)
  const latex = (found as string | null)?.trim() ?? null
  return latex && isLatex(latex) ? latex : null
}

/**
 * Formulas (approved 2026-10-26): the document keeps the LaTeX source; the
 * HTML is MathML generated by KaTeX from it (every browser shows it, no
 * script needed), with the LaTeX in an annotation. Reading HTML takes only
 * that annotation: the MathML that comes in is never kept, it is generated
 * again. `math_inline` in the text, `math_display` as its own block.
 */
export function createMathNodes(katex: MathRenderer): {
  math_inline: NodeSpec
  math_display: NodeSpec
} {
  const renderTree = treeRenderer(katex)
  // the HTML is written on every change: each formula is rendered once (most recent kept)
  const cache = new Map<string, HTMLSpec>()
  const spec = (node: Node, display: boolean): HTMLSpec => {
    const latex = node.attrs['latex'] as string
    const key = `${display ? 'b' : 'i'}${latex}`
    const cached = cache.get(key)
    if (cached) return cached
    const made = render(latex, display)
    if (cache.size >= 500) cache.delete(cache.keys().next().value!)
    cache.set(key, made)
    return made
  }
  const render = (latex: string, display: boolean): HTMLSpec => {
    let tree: unknown = null
    try {
      tree = renderTree(latex, katexOptions(display))
    } catch {
      tree = null // too complex, or a KaTeX error: the source stays readable below
    }
    const math = tree ? mathmlSpec(tree) : null
    if (math) return math
    // fallback: an empty formula with its source (valid MathML, read back the same)
    return [
      'math',
      { xmlns: 'http://www.w3.org/1998/Math/MathML', ...(display ? { display: 'block' } : {}) },
      ['semantics', ['mrow'], ['annotation', { encoding: 'application/x-tex' }, latex]],
    ]
  }
  const rule = (display: boolean) => ({
    tag: 'math',
    getAttrs: (el: DOMLikeElement) => {
      if ((el.getAttribute('display') === 'block') !== display) return false
      const latex = latexOf(el)
      return latex ? { latex } : false
    },
  })
  return {
    math_inline: {
      inline: true,
      group: 'inline',
      atom: true,
      attrs: { latex: { validate: isLatex } },
      leafText: (node) => `$${node.attrs['latex'] as string}$`,
      parseHTML: [rule(false)],
      toHTML: (node) => spec(node, false),
    },
    math_display: {
      group: 'block',
      atom: true,
      attrs: { latex: { validate: isLatex } },
      leafText: (node) => `$$${node.attrs['latex'] as string}$$`,
      parseHTML: [rule(true)],
      toHTML: (node) => spec(node, true),
    },
  }
}
